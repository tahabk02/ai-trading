export const t = (
  lang: Lang,
  key: keyof (typeof translations)["en"],
  params?: Record<string, string | number>,
): string => {
  const value = translations[lang]?.[key] ?? translations.en[key] ?? String(key);
  if (typeof value !== "string" || !params) return value;
  // Interpolate `{placeholder}` tokens (used for dynamic reasoning strings).
  // Values are escaped for safety so a numeric/price fragment can never
  // inject markup.
  return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    const v = params[name];
    return v === undefined ? match : String(v);
  });
};

export const isRTL = (lang: Lang) => lang === "ar";

